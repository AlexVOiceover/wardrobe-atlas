"""Draws the Wardrobe Atlas launcher icon and writes its Android vector files.

Five T-shirts stand side by side in perspective, all white except the middle
one, which is amber and lifted: the garment the app helps you find. Each
shirt's visible part is computed so the shirts never overlap and a real gap
separates them, which keeps the single-colour themed icon readable.

Run from the repository root (needs shapely: pip install shapely):
    python3 features/app-icon/generate_icon.py
"""
import math
from pathlib import Path

from shapely.geometry import Polygon
from shapely.ops import unary_union
from shapely import affinity

RES = Path("android/app/src/main/res")
WHITE, AMBER, TEAL = "#FFFFFF", "#F2B35B", "#1F4E5A"

from shapely.geometry import Polygon, Point
from shapely.ops import unary_union
from shapely import affinity

def quad(p0, p1, p2, n=10):
    return [((1-t)**2*p0[0]+2*(1-t)*t*p1[0]+t*t*p2[0], (1-t)**2*p0[1]+2*(1-t)*t*p1[1]+t*t*p2[1]) for t in [i/n for i in range(1, n+1)]]

def shirt():
    # Front view T-shirt, centred on 0,0; 56 wide, 37 tall.
    pts = [(45,42),(32,47.5),(26,59),(34.5,63),(38.5,56.5),(38.5,77)]
    pts += quad((38.5,77),(38.5,79),(40.5,79),4)
    pts += [(67.5,79)] + quad((67.5,79),(69.5,79),(69.5,77),4)
    pts += [(69.5,56.5),(73.5,63),(82,59),(76,47.5),(63,42)]
    pts += quad((63,42),(54,52),(45,42),12)[:-1]
    return affinity.translate(Polygon(pts), -54, -60.5)

def build(n, highlight, place, gap, lift=0):
    shapes = []
    for i in range(n):
        s = place(shirt(), i)
        if i == highlight and lift: s = affinity.translate(s, 0, -lift)
        shapes.append(s)
    # Fit into the safe zone: centre the bounding box, then scale so every point is within r=31 of 54,54.
    allu = unary_union(shapes)
    minx, miny, maxx, maxy = allu.bounds
    cx, cy = (minx+maxx)/2, (miny+maxy)/2
    shapes = [affinity.translate(s, 54-cx, 54-cy) for s in shapes]
    pts = [p for s in shapes for p in s.exterior.coords]
    r = max(math.hypot(x-54, y-54) for x, y in pts)
    k = 31/r
    shapes = [affinity.scale(s, k, k, origin=(54,54)) for s in shapes]
    out = []
    for i, s in enumerate(shapes):
        front = unary_union(shapes[i+1:]) if i+1 < n else None
        vis = s.difference(front.buffer(gap*k, join_style=1)) if front else s
        out.append({"d": to_path(vis), "hi": i == highlight})
    return out

def ring(coords):
    c = list(coords)[:-1]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in c) + " Z"

def to_path(g):
    geoms = getattr(g, "geoms", [g])
    parts = []
    for p in geoms:
        if p.is_empty or p.area < 0.5: continue
        parts.append(ring(p.exterior.coords))
        parts += [ring(h.coords) for h in p.interiors]
    return " ".join(parts)

def perspective(scale_x, skew_deg, step):
    """Turns each shirt sideways and places it one step to the right."""
    def place(s, i):
        s = affinity.scale(s, scale_x, 1, origin=(0, 0))
        s = affinity.affine_transform(s, [1, 0, math.tan(math.radians(skew_deg)), 1, 0, 0])
        return affinity.translate(s, i * step, 0)
    return place


def vector(body, comment):
    return (
        f"<!-- {comment} Generated by features/app-icon/generate_icon.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        'android:width="108dp" android:height="108dp" '
        'android:viewportWidth="108" android:viewportHeight="108">\n'
        f"{body}</vector>\n"
    )


def paths(shirts, indent, mono=False):
    return "".join(
        f'{indent}<path android:fillType="evenOdd" android:fillColor="'
        f'{WHITE if mono or not s["hi"] else AMBER}" android:pathData="{s["d"]}" />\n'
        for s in shirts
    )


def legacy(shirts, background):
    return vector(
        f'    <path android:fillColor="{TEAL}" android:pathData="{background}" />\n'
        '    <group android:pivotX="54" android:pivotY="54" android:scaleX="1.4" android:scaleY="1.4">\n'
        + paths(shirts, "        ")
        + "    </group>\n",
        "Icon for Android 7 (no adaptive icons): the same design, scaled to fill the canvas.",
    )


if __name__ == "__main__":
    shirts = build(5, 2, perspective(0.55, 22, 13), gap=3, lift=12)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(
        paths(shirts, "    "),
        "Launcher icon foreground: five T-shirts side by side, the middle one amber and lifted.",
    ))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(
        paths(shirts, "    ", mono=True),
        "Themed icon (Android 13+): only the shape counts, the phone picks the colour.",
    ))
    (RES / "mipmap-anydpi/ic_launcher.xml").write_text(legacy(
        shirts, "M24,0 H84 A24,24 0 0 1 108,24 V84 A24,24 0 0 1 84,108 H24 A24,24 0 0 1 0,84 V24 A24,24 0 0 1 24,0 Z"))
    (RES / "mipmap-anydpi/ic_launcher_round.xml").write_text(legacy(
        shirts, "M54,0 A54,54 0,1 1,54,108 A54,54 0,1 1,54,0"))
